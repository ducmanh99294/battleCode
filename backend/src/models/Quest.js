const mongoose = require("mongoose");

const questSchema = new mongoose.Schema(
  {
    /*
    |--------------------------------------------------------------------------
    | Basic Information
    |--------------------------------------------------------------------------
    */

    name: {
      type: String,
      required: true,
      trim: true,
      maxlength: 150,
    },

    description: {
      type: String,
      default: "",
      trim: true,
    },

    icon: {
      type: String,
      default: "",
    },

    /*
    |--------------------------------------------------------------------------
    | Quest Type
    |--------------------------------------------------------------------------
    */

    type: {
      type: String,
      enum: [
        "main",
        "side",
        "daily",
        "event",
      ],
      default: "side",
    },

    /*
    |--------------------------------------------------------------------------
    | Level Requirement
    |--------------------------------------------------------------------------
    */

    requiredLevel: {
      type: Number,
      default: 1,
      min: 1,
    },

    /*
    |--------------------------------------------------------------------------
    | Time Limit
    |--------------------------------------------------------------------------
    |
    | Đơn vị: seconds
    |
    | 0 = không giới hạn
    |
    */

    timeLimit: {
      type: Number,
      default: 0,
      min: 0,
    },

    /*
    |--------------------------------------------------------------------------
    | Objectives
    |--------------------------------------------------------------------------
    */

    objectives: [
      {
        type: {
          type: String,
          enum: [
            "kill",
            "collect",
            "talk",
            "reach",
            "use_item",
          ],
          required: true,
        },

        /*
        |--------------------------------------------------------------------------
        | Target
        |--------------------------------------------------------------------------
        |
        | Ví dụ:
        |
        | kill → Slime
        | collect → SlimeGel
        | talk → NPC
        |
        */

        targetId: {
          type: mongoose.Schema.Types.ObjectId,
          default: null,
        },

        targetName: {
          type: String,
          default: "",
        },

        /*
        |--------------------------------------------------------------------------
        | Required Amount
        |--------------------------------------------------------------------------
        */

        required: {
          type: Number,
          default: 1,
          min: 1,
        },

        /*
        |--------------------------------------------------------------------------
        | Objective Description
        |--------------------------------------------------------------------------
        */

        description: {
          type: String,
          default: "",
        },
      },
    ],

    /*
    |--------------------------------------------------------------------------
    | Reward
    |--------------------------------------------------------------------------
    */

    reward: {
      gold: {
        type: Number,
        default: 0,
        min: 0,
      },

      exp: {
        type: Number,
        default: 0,
        min: 0,
      },

      /*
      |--------------------------------------------------------------------------
      | Item Rewards
      |--------------------------------------------------------------------------
      */

      items: [
        {
          itemId: {
            type: mongoose.Schema.Types.ObjectId,
            ref: "Item",
            required: true,
          },

          amount: {
            type: Number,
            default: 1,
            min: 1,
          },
        },
      ],

      /*
      |--------------------------------------------------------------------------
      | Skill Reward
      |--------------------------------------------------------------------------
      */

      skills: [
        {
          type: mongoose.Schema.Types.ObjectId,
          ref: "Skill",
        },
      ],
    },

    /*
    |--------------------------------------------------------------------------
    | Repeatable
    |--------------------------------------------------------------------------
    */

    repeatable: {
      type: Boolean,
      default: false,
    },

    /*
    |--------------------------------------------------------------------------
    | Active
    |--------------------------------------------------------------------------
    */

    isActive: {
      type: Boolean,
      default: true,
    },
  },
  {
    timestamps: true,
  }
);

module.exports = mongoose.model("Quest", questSchema);
