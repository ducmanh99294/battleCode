const mongoose = require("mongoose");

const skillSchema = new mongoose.Schema(
  {
    // Tên skill
    name: {
      type: String,
      required: true,
      trim: true,
      maxlength: 100,
    },

    // Mô tả
    description: {
      type: String,
      default: "",
      trim: true,
    },

    // Icon skill
    icon: {
      type: String,
      default: "",
    },

    /*
    |--------------------------------------------------------------------------
    | Skill Type
    |--------------------------------------------------------------------------
    */

    type: {
      type: String,
      enum: [
        "active",
        "passive",
      ],
      default: "active",
    },

    /*
    |--------------------------------------------------------------------------
    | Damage / Effect
    |--------------------------------------------------------------------------
    */

    damageType: {
      type: String,
      enum: [
        "physical",
        "magic",
        "true",
        "none",
      ],
      default: "none",
    },

    power: {
      type: Number,
      default: 0,
      min: 0,
    },

    /*
    |--------------------------------------------------------------------------
    | Resource Cost
    |--------------------------------------------------------------------------
    */

    manaCost: {
      type: Number,
      default: 0,
      min: 0,
    },

    energyCost: {
      type: Number,
      default: 0,
      min: 0,
    },

    /*
    |--------------------------------------------------------------------------
    | Cooldown
    |--------------------------------------------------------------------------
    */

    cooldown: {
      type: Number,
      default: 0,
      min: 0,
    },

    /*
    |--------------------------------------------------------------------------
    | Range
    |--------------------------------------------------------------------------
    */

    range: {
      type: Number,
      default: 1,
      min: 0,
    },

    /*
    |--------------------------------------------------------------------------
    | Required Level
    |--------------------------------------------------------------------------
    */

    requiredLevel: {
      type: Number,
      default: 1,
      min: 1,
    },

    /*
    |--------------------------------------------------------------------------
    | Maximum Skill Level
    |--------------------------------------------------------------------------
    */

    maxLevel: {
      type: Number,
      default: 5,
      min: 1,
    },

    /*
    |--------------------------------------------------------------------------
    | Scaling
    |--------------------------------------------------------------------------
    |
    | Xác định skill tăng sức mạnh dựa trên stat nào.
    |
    */

    scalingStat: {
      type: String,
      enum: [
        "STR",
        "VIT",
        "AGI",
        "INT",
        "END",
        "LUK",
        "none",
      ],
      default: "none",
    },

    /*
    |--------------------------------------------------------------------------
    | Skill Level Scaling
    |--------------------------------------------------------------------------
    |
    | Ví dụ:
    | level 1 = 100%
    | mỗi level +20%
    |
    */

    levelMultiplier: {
      type: Number,
      default: 0.2,
      min: 0,
    },

    /*
    |--------------------------------------------------------------------------
    | Animation
    |--------------------------------------------------------------------------
    */

    animation: {
      type: String,
      default: "",
    },

    /*
    |--------------------------------------------------------------------------
    | VFX
    |--------------------------------------------------------------------------
    */

    effect: {
      type: String,
      default: "",
    },

    /*
    |--------------------------------------------------------------------------
    | Unlock Information
    |--------------------------------------------------------------------------
    |
    | Skill có thể được học từ:
    | - monster drop
    | - quest
    | - item
    | - level
    |
    */

    unlockType: {
      type: String,
      enum: [
        "monster_drop",
        "quest",
        "item",
        "level",
        "default",
      ],
      default: "monster_drop",
    },

    /*
    |--------------------------------------------------------------------------
    | Active
    |--------------------------------------------------------------------------
    */

    isActive: {
      type: Boolean,
      default: true,
    },
  },
  {
    timestamps: true,
  }
);

module.exports = mongoose.model("Skill", skillSchema);